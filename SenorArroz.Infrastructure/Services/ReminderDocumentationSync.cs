using System.Net;
using System.Net.Http.Headers;
using System.Net.Http.Json;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using SenorArroz.Application.Common.Interfaces;
using SenorArroz.Application.Features.OperationalChecklist;
using SenorArroz.Domain.Entities;
using SenorArroz.Infrastructure.Data;

namespace SenorArroz.Infrastructure.Services;

public sealed class ReminderDocumentationOptions
{
    public int TenantId { get; set; }
    public string GitHubToken { get; set; } = string.Empty;
    public string Repository { get; set; } = "savelasquezs/senorarrozGuide";
    public string Branch { get; set; } = "manual-interno-protegido";
}

// Only this generated snippet is writable; ordinary manual pages are never replaced.
public sealed class ReminderDocumentationSync(HttpClient http, ApplicationDbContext db, ICurrentTenant tenant,
    IOptions<ReminderDocumentationOptions> options, ILogger<ReminderDocumentationSync> logger) : IReminderDocumentationSync
{
    public const string TargetPath = "snippets/operational-checklist.mdx";
    public const string Marker = "{/* GENERATED BY SENOR ARROZ POS: OPERATIONAL CHECKLIST */}";
    private static readonly SemaphoreSlim PublishLock = new(1, 1);

    public async Task<ReminderSyncResult> SyncAsync(CancellationToken ct)
    {
        var config = options.Value;
        if (config.TenantId <= 0 || tenant.TenantId != config.TenantId || string.IsNullOrWhiteSpace(config.GitHubToken)
            || !Regex.IsMatch(config.Repository, "^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$") || string.IsNullOrWhiteSpace(config.Branch))
            return new("notConfigured", "Guardado en el POS. La conexión de publicación a Mintlify todavía no está configurada.");
        await PublishLock.WaitAsync(ct);
        try
        {
            var endpoint = $"https://api.github.com/repos/{config.Repository}/contents/{TargetPath}";
            // A SHA conflict means another publication won. Reload both GitHub and PostgreSQL before retrying.
            for (var attempt = 0; attempt < 3; attempt++)
            {
                using var read = Request(HttpMethod.Get, endpoint + "?ref=" + Uri.EscapeDataString(config.Branch), config.GitHubToken);
                using var response = await http.SendAsync(read, ct);
                string? sha = null, oldContent = null;
                if (response.StatusCode != HttpStatusCode.NotFound)
                {
                    response.EnsureSuccessStatusCode();
                    using var json = JsonDocument.Parse(await response.Content.ReadAsStringAsync(ct));
                    sha = json.RootElement.GetProperty("sha").GetString();
                    oldContent = Encoding.UTF8.GetString(Convert.FromBase64String(json.RootElement.GetProperty("content").GetString()!));
                    if (!oldContent.StartsWith(Marker, StringComparison.Ordinal))
                        return new("pending", "No se publicó: el archivo de destino contiene texto manual. Revisar la integración antes de reemplazarlo.");
                }
                var rows = await db.OperationalReminders.AsNoTracking().OrderBy(x => x.BranchId)
                    .ThenBy(x => x.SortOrder).ThenBy(x => x.Id).ToListAsync(ct);
                var names = await db.Branches.AsNoTracking().ToDictionaryAsync(x => x.Id, x => x.Name, ct);
                var content = Render(rows, names);
                if (content != oldContent)
                {
                    using var write = Request(HttpMethod.Put, endpoint, config.GitHubToken);
                    write.Content = JsonContent.Create(new { message = "docs(checklist): sincronizar configuración del POS", branch = config.Branch,
                        sha, content = Convert.ToBase64String(Encoding.UTF8.GetBytes(content)) });
                    using var published = await http.SendAsync(write, ct);
                    if (published.StatusCode == HttpStatusCode.Conflict) continue;
                    published.EnsureSuccessStatusCode();
                }
                foreach (var row in rows)
                    await db.OperationalReminders.Where(x => x.Id == row.Id && x.Revision == row.Revision)
                        .ExecuteUpdateAsync(s => s.SetProperty(x => x.SyncedRevision, row.Revision), ct);
                return new("synced", "Tablas enviadas al repositorio del manual. Mintlify las mostrará cuando termine su publicación.");
            }
        }
        catch (OperationCanceledException) when (ct.IsCancellationRequested) { throw; }
        catch (Exception e)
        {
            // Do not log request headers, tokens or the manual's contents.
            logger.LogWarning("Reminder documentation publication pending ({ErrorType})", e.GetType().Name);
        }
        finally { PublishLock.Release(); }
        return new("pending", "Guardado en el POS. Mintlify está pendiente; usa Sincronizar para reintentar.");
    }

    private static HttpRequestMessage Request(HttpMethod method, string url, string token)
    {
        var request = new HttpRequestMessage(method, url);
        request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", token);
        request.Headers.UserAgent.ParseAdd("SenorArroz-Checklist/1.0");
        request.Headers.Accept.ParseAdd("application/vnd.github+json");
        request.Headers.Add("X-GitHub-Api-Version", "2022-11-28");
        return request;
    }

    public static string Render(IEnumerable<OperationalReminder> reminders, IReadOnlyDictionary<int, string> branches)
    {
        var text = new StringBuilder(Marker + "\n\n");
        text.AppendLine("La configuración se edita en el POS. Los checks son opcionales y se comparten por sucursal; no hay historial de cumplimiento. Los miércoles no hay recordatorios.\n");
        foreach (var group in reminders.GroupBy(x => x.BranchId).OrderBy(x => x.Key))
        {
            text.AppendLine("## " + Cell(branches.GetValueOrDefault(group.Key, $"Sucursal {group.Key}")) + "\n");
            foreach (var period in new[] { "morning", "evening" })
            {
                text.AppendLine(period == "morning" ? "### Mañana · 10:30 a. m.\n" : "### Tarde · 6:00 p. m.\n");
                text.AppendLine("| Día | Tarea | Descripción | Condición | Responsable | Procedimiento |");
                text.AppendLine("| --- | --- | --- | --- | --- | --- |");
                foreach (var item in group.Where(x => x.IsActive && x.Period == period).OrderBy(x => x.SortOrder).ThenBy(x => x.Id))
                    text.AppendLine($"| {Cell(Days(item))} | {Cell(item.Title)} | {Cell(item.Description)} | {Cell(item.Condition)} | {(item.Responsible == "admin" ? "Administración" : "Cajero")} | [Consultar]({item.ManualPath}) |");
                text.AppendLine();
            }
        }
        return text.ToString().Replace("\r\n", "\n");
    }

    private static string Days(OperationalReminder item)
    {
        if (item.ShiftMondayHoliday) return "Lunes; martes si el lunes es festivo";
        if (item.DaysOfWeek.Order().SequenceEqual(new[] { 0, 1, 2, 4, 5, 6 })) return "Todos los días de operación";
        string[] names = ["Domingo", "Lunes", "Martes", "Miércoles", "Jueves", "Viernes", "Sábado"];
        return string.Join(", ", item.DaysOfWeek.Order().Select(x => names[x]));
    }
    private static string Cell(string value) => WebUtility.HtmlEncode(value).Replace("{", "&#123;").Replace("}", "&#125;")
        .Replace("|", "&#124;").Replace("[", "&#91;").Replace("]", "&#93;").Replace("`", "&#96;")
        .Replace("*", "&#42;").Replace("_", "&#95;").Replace("$", "&#36;").Replace("\r", "").Replace("\n", "<br />");
}
