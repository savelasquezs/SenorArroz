-- Execute against Railway MainDatabase BEFORE deploying the kitchen voice inbox API.
-- Idempotent; intentionally no backfill of historical orders.
BEGIN;

CREATE TABLE IF NOT EXISTS public.kitchen_voice_event (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES public.tenant(id),
    branch_id integer NOT NULL REFERENCES public.branch(id),
    order_id integer NOT NULL REFERENCES public."order"(id) ON DELETE CASCADE,
    kind character varying(24) NOT NULL CHECK (kind IN ('new', 'reservation')),
    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
    updated_at timestamp with time zone NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_kitchen_voice_event_tenant_order
    ON public.kitchen_voice_event (tenant_id, order_id);
CREATE INDEX IF NOT EXISTS ix_kitchen_voice_event_tenant_branch_cursor
    ON public.kitchen_voice_event (tenant_id, branch_id, id);

ALTER TABLE public.kitchen_voice_event ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.kitchen_voice_event FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_select_policy ON public.kitchen_voice_event;
CREATE POLICY tenant_select_policy ON public.kitchen_voice_event
    FOR SELECT USING (app.is_system_scope() OR tenant_id = app.current_tenant_id());
DROP POLICY IF EXISTS tenant_insert_policy ON public.kitchen_voice_event;
CREATE POLICY tenant_insert_policy ON public.kitchen_voice_event
    FOR INSERT WITH CHECK (app.is_system_scope() OR tenant_id = app.current_tenant_id());

DO $grant$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'senorarroz_runtime') THEN
        GRANT SELECT, INSERT ON public.kitchen_voice_event TO senorarroz_runtime;
        GRANT USAGE, SELECT ON SEQUENCE public.kitchen_voice_event_id_seq TO senorarroz_runtime;
    END IF;
END $grant$;

COMMIT;

