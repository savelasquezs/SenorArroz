-- Apply BEFORE deploying the atomic POS backend/frontend. Metadata only: no legacy backfill.
-- Requires PostgreSQL schema-owner connection; never run from the restricted runtime role.
BEGIN;
ALTER TABLE public."order" ADD COLUMN IF NOT EXISTS pos_creation_key varchar(80);
ALTER TABLE public."order" ADD COLUMN IF NOT EXISTS pos_creation_fingerprint varchar(64);

-- Null legacy rows remain valid. One committed order per tenant and POS request key.
CREATE UNIQUE INDEX IF NOT EXISTS ux_order_pos_creation_tenant
    ON public."order" (tenant_id, pos_creation_key)
    WHERE pos_creation_key IS NOT NULL;

COMMENT ON COLUMN public."order".pos_creation_key
    IS 'Stable UUID generated by POS before first submit; retries must not create a second order.';
COMMENT ON COLUMN public."order".pos_creation_fingerprint
    IS 'Server SHA-256 of the original POS CreateOrderDto; reject key reused with changed payload.';
COMMIT;

