BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL app.system_scope = 'on';

ALTER TABLE public.whatsapp_conversation
    ADD COLUMN IF NOT EXISTS is_supplier boolean NOT NULL DEFAULT false,
    ADD COLUMN IF NOT EXISTS pending_order_marked_at timestamptz,
    ADD COLUMN IF NOT EXISTS is_payment_pending boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.whatsapp_inbox_taken_reset (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES public.tenant(id) ON DELETE RESTRICT,
    scope_branch_id integer NOT NULL CHECK (scope_branch_id >= 0),
    cleared_before timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, scope_branch_id)
);
CREATE INDEX IF NOT EXISTS ix_order_whatsapp_inbox_date
    ON public."order"(tenant_id, whatsapp_conversation_id, created_at DESC, id DESC)
    WHERE whatsapp_conversation_id IS NOT NULL AND status NOT IN ('cancelled', 'awaiting_payment');
CREATE INDEX IF NOT EXISTS ix_whatsapp_inbox_taken_reset_tenant
    ON public.whatsapp_inbox_taken_reset(tenant_id);

ALTER TABLE public.whatsapp_inbox_taken_reset ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_inbox_taken_reset FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_select_policy ON public.whatsapp_inbox_taken_reset;
DROP POLICY IF EXISTS tenant_insert_policy ON public.whatsapp_inbox_taken_reset;
DROP POLICY IF EXISTS tenant_update_policy ON public.whatsapp_inbox_taken_reset;
DROP POLICY IF EXISTS tenant_delete_policy ON public.whatsapp_inbox_taken_reset;
CREATE POLICY tenant_select_policy ON public.whatsapp_inbox_taken_reset FOR SELECT
    USING (app.is_system_scope() OR tenant_id = app.current_tenant_id());
CREATE POLICY tenant_insert_policy ON public.whatsapp_inbox_taken_reset FOR INSERT
    WITH CHECK (app.is_system_scope() OR tenant_id = app.current_tenant_id());
CREATE POLICY tenant_update_policy ON public.whatsapp_inbox_taken_reset FOR UPDATE
    USING (app.is_system_scope() OR tenant_id = app.current_tenant_id())
    WITH CHECK (app.is_system_scope() OR tenant_id = app.current_tenant_id());
CREATE POLICY tenant_delete_policy ON public.whatsapp_inbox_taken_reset FOR DELETE
    USING (app.is_system_scope() OR tenant_id = app.current_tenant_id());

INSERT INTO public.whatsapp_inbox_taken_reset (tenant_id, scope_branch_id, cleared_before)
SELECT scope.tenant_id, scope.branch_id, date_trunc('day', now() AT TIME ZONE 'America/Bogota') AT TIME ZONE 'America/Bogota'
FROM (
    SELECT tenant_id, id AS branch_id FROM public.branch
    UNION ALL
    SELECT id, 0 FROM public.tenant
) AS scope
ON CONFLICT (tenant_id, scope_branch_id) DO NOTHING;

DO $$
BEGIN
    IF to_regrole('senorarroz_runtime') IS NOT NULL THEN
        GRANT SELECT, INSERT, UPDATE ON public.whatsapp_inbox_taken_reset TO senorarroz_runtime;
        GRANT USAGE ON SEQUENCE public.whatsapp_inbox_taken_reset_id_seq TO senorarroz_runtime;
    END IF;
END $$;

COMMIT;
