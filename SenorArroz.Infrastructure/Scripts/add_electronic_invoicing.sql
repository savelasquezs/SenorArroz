CREATE OR REPLACE FUNCTION prevent_invoiced_order_mutation() RETURNS trigger LANGUAGE plpgsql AS $guard$
DECLARE target_id integer; target_tenant integer;
BEGIN
 IF TG_TABLE_NAME='order' THEN
  target_id:=OLD.id; target_tenant:=OLD.tenant_id;
  IF TG_OP='UPDATE' AND (NEW.total,NEW.subtotal,NEW.discount_total,NEW.delivery_fee,NEW.customer_id)
    IS NOT DISTINCT FROM (OLD.total,OLD.subtotal,OLD.discount_total,OLD.delivery_fee,OLD.customer_id) THEN RETURN NEW; END IF;
 ELSE
  IF TG_OP='UPDATE' AND (NEW.order_id,NEW.product_id,NEW.quantity,NEW.unit_price,NEW.discount,NEW.subtotal,NEW.tenant_id)
    IS NOT DISTINCT FROM (OLD.order_id,OLD.product_id,OLD.quantity,OLD.unit_price,OLD.discount,OLD.subtotal,OLD.tenant_id) THEN RETURN NEW; END IF;
  target_id:=COALESCE(NEW.order_id,OLD.order_id); target_tenant:=COALESCE(NEW.tenant_id,OLD.tenant_id);
  IF TG_OP='UPDATE' AND NEW.order_id<>OLD.order_id AND EXISTS(SELECT 1 FROM electronic_invoice_document
    WHERE tenant_id=OLD.tenant_id AND order_id=OLD.order_id AND kind='invoice' AND status IN ('pending','processing','verifying','issued')) THEN
   RAISE EXCEPTION 'No se pueden mover líneas de un pedido facturado.' USING ERRCODE='23514', CONSTRAINT='electronic_invoice_order_locked';
  END IF;
 END IF;
 IF EXISTS(SELECT 1 FROM electronic_invoice_document WHERE tenant_id=target_tenant AND order_id=target_id
   AND (TG_OP='DELETE' AND TG_TABLE_NAME='order' OR kind='invoice' AND status IN ('pending','processing','verifying','issued'))) THEN
  RAISE EXCEPTION 'El pedido tiene documentos fiscales. Espera la confirmación o anula la factura mediante nota crédito.' USING ERRCODE='23514', CONSTRAINT='electronic_invoice_order_locked';
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END $guard$;
DROP TRIGGER IF EXISTS protect_invoiced_order ON public."order";
CREATE TRIGGER protect_invoiced_order BEFORE UPDATE OR DELETE ON public."order" FOR EACH ROW EXECUTE FUNCTION prevent_invoiced_order_mutation();
DROP TRIGGER IF EXISTS protect_invoiced_order_detail ON order_detail;
CREATE TRIGGER protect_invoiced_order_detail BEFORE INSERT OR UPDATE OR DELETE ON order_detail FOR EACH ROW EXECUTE FUNCTION prevent_invoiced_order_mutation();
