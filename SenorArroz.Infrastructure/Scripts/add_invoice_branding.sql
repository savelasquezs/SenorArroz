BEGIN;
CREATE TABLE IF NOT EXISTS electronic_invoice_branding (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id integer NOT NULL REFERENCES tenant(id) ON DELETE RESTRICT,
 display_name varchar(150) NOT NULL,
 logo bytea NOT NULL CHECK(octet_length(logo) BETWEEN 1 AND 500000),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id,id)
);
CREATE INDEX IF NOT EXISTS ix_invoice_branding_tenant ON electronic_invoice_branding(tenant_id,id DESC);
ALTER TABLE electronic_invoice_document ADD COLUMN IF NOT EXISTS branding_id integer;
DO $constraint$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_invoice_document_branding') THEN
  ALTER TABLE electronic_invoice_document ADD CONSTRAINT fk_invoice_document_branding
   FOREIGN KEY(tenant_id,branding_id) REFERENCES electronic_invoice_branding(tenant_id,id) ON DELETE RESTRICT;
 END IF;
END $constraint$;
ALTER TABLE electronic_invoice_branding ENABLE ROW LEVEL SECURITY;
ALTER TABLE electronic_invoice_branding FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON electronic_invoice_branding;
CREATE POLICY tenant_isolation ON electronic_invoice_branding
 USING (app.is_system_scope() OR tenant_id=app.current_tenant_id())
 WITH CHECK (app.is_system_scope() OR tenant_id=app.current_tenant_id());
CREATE OR REPLACE FUNCTION preserve_invoice_branding() RETURNS trigger LANGUAGE plpgsql AS $guard$
BEGIN
 RAISE EXCEPTION 'La identidad visual se conserva por versión. Registra una nueva versión.' USING ERRCODE='23514';
END $guard$;
DROP TRIGGER IF EXISTS preserve_invoice_branding ON electronic_invoice_branding;
CREATE TRIGGER preserve_invoice_branding BEFORE UPDATE OR DELETE ON electronic_invoice_branding
 FOR EACH ROW EXECUTE FUNCTION preserve_invoice_branding();
DO $grants$
BEGIN
 IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='senorarroz_runtime') THEN
  GRANT SELECT,INSERT ON electronic_invoice_branding TO senorarroz_runtime;
  GRANT USAGE,SELECT ON SEQUENCE electronic_invoice_branding_id_seq TO senorarroz_runtime;
 END IF;
END $grants$;
COMMIT;
