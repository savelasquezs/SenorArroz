-- Additive, idempotent. Apply before deploying the API. No existing business data is modified.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
CREATE TABLE IF NOT EXISTS public.operational_reminder (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES public.tenant(id),
    branch_id integer NOT NULL,
    code varchar(64) NOT NULL,
    title varchar(160) NOT NULL,
    description varchar(2000) NOT NULL,
    condition_text varchar(500) NOT NULL DEFAULT '',
    period varchar(10) NOT NULL CHECK (period IN ('morning','evening')),
    days_of_week integer[] NOT NULL CHECK (cardinality(days_of_week) BETWEEN 1 AND 6 AND days_of_week <@ ARRAY[0,1,2,4,5,6]),
    shift_monday_holiday boolean NOT NULL DEFAULT false,
    responsible varchar(12) NOT NULL CHECK (responsible IN ('cashier','admin')),
    manual_path varchar(250) NOT NULL,
    sort_order integer NOT NULL DEFAULT 0 CHECK(sort_order BETWEEN 0 AND 1000),
    is_active boolean NOT NULL DEFAULT true,
    revision bigint NOT NULL DEFAULT 1,
    synced_revision bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id,branch_id,id),
    UNIQUE (tenant_id,branch_id,code),
    FOREIGN KEY (tenant_id,branch_id) REFERENCES public.branch(tenant_id,id)
);
CREATE TABLE IF NOT EXISTS public.operational_reminder_state (
    tenant_id integer NOT NULL,
    reminder_id integer NOT NULL,
    branch_id integer NOT NULL,
    operation_date date,
    is_checked boolean NOT NULL DEFAULT false,
    revision bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (tenant_id,reminder_id),
    FOREIGN KEY (tenant_id,branch_id,reminder_id) REFERENCES public.operational_reminder(tenant_id,branch_id,id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_operational_reminder_tenant ON public.operational_reminder(tenant_id);
CREATE INDEX IF NOT EXISTS ix_operational_reminder_state_branch ON public.operational_reminder_state(tenant_id,branch_id);
DO $$
DECLARE tbl text;
BEGIN
  FOREACH tbl IN ARRAY ARRAY['operational_reminder','operational_reminder_state'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',tbl);
    EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY',tbl);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON public.%I',tbl);
    EXECUTE format('CREATE POLICY tenant_isolation ON public.%I USING (tenant_id = app.current_tenant_id() OR app.is_system_scope()) WITH CHECK (tenant_id = app.current_tenant_id() OR app.is_system_scope())',tbl);
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='senorarroz_runtime') THEN
      EXECUTE format('GRANT SELECT,INSERT,UPDATE ON public.%I TO senorarroz_runtime',tbl);
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='senorarroz_runtime') THEN
    GRANT USAGE,SELECT ON SEQUENCE public.operational_reminder_id_seq TO senorarroz_runtime;
  END IF;
END $$;
COMMIT;
