BEGIN;

CREATE TABLE IF NOT EXISTS delivery_authorized_place (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id integer NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
    name varchar(100) NOT NULL,
    latitude numeric(10,6) NOT NULL,
    longitude numeric(10,6) NOT NULL,
    radius_meters integer NOT NULL DEFAULT 50,
    active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_delivery_authorized_place_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_delivery_authorized_place_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_delivery_authorized_place_radius CHECK (radius_meters BETWEEN 1 AND 5000)
);

CREATE INDEX IF NOT EXISTS idx_delivery_authorized_place_branch_active
    ON delivery_authorized_place(branch_id, active);

ALTER TABLE delivery_stay
    ADD COLUMN IF NOT EXISTS authorized_place_id integer
        REFERENCES delivery_authorized_place(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS distance_to_authorized_place_meters double precision,
    ADD COLUMN IF NOT EXISTS classification varchar(40) NOT NULL DEFAULT 'pending_review',
    ADD COLUMN IF NOT EXISTS classification_reason varchar(300),
    ADD COLUMN IF NOT EXISTS classified_at timestamp with time zone;

CREATE INDEX IF NOT EXISTS idx_delivery_stay_classification
    ON delivery_stay(classification, classified_at);

CREATE INDEX IF NOT EXISTS idx_delivery_stay_authorized_place
    ON delivery_stay(authorized_place_id);

COMMIT;
