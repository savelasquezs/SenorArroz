CREATE TABLE IF NOT EXISTS public.employee_leave_request (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES public.tenant(id),
    public_id uuid NOT NULL,
    request_key uuid NOT NULL,
    user_id integer NOT NULL,
    branch_id integer NOT NULL,
    applicant_name varchar(150) NOT NULL,
    applicant_role varchar(32) NOT NULL,
    document_number varchar(32),
    kind varchar(40) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'pending',
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    justification varchar(2000) NOT NULL,
    is_paid boolean,
    decided_by_user_id integer,
    decided_at timestamptz,
    decision_reason varchar(1000),
    support_required boolean NOT NULL DEFAULT false,
    support_due_at timestamptz,
    support_status varchar(20) NOT NULL DEFAULT 'not_required',
    returned_at timestamptz,
    return_verified_at timestamptz,
    return_verified_by_user_id integer,
    verification_reason varchar(1000),
    version bigint NOT NULL DEFAULT 1,
    last_read_version bigint NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, id),
    UNIQUE (tenant_id, public_id),
    UNIQUE (tenant_id, user_id, request_key),
    FOREIGN KEY (tenant_id, user_id) REFERENCES public."user"(tenant_id, id),
    FOREIGN KEY (tenant_id, branch_id) REFERENCES public.branch(tenant_id, id),
    FOREIGN KEY (tenant_id, decided_by_user_id) REFERENCES public."user"(tenant_id, id),
    FOREIGN KEY (tenant_id, return_verified_by_user_id) REFERENCES public."user"(tenant_id, id),
    CHECK (ends_at > starts_at AND ends_at <= starts_at + interval '366 days'),
    CHECK (version > 0 AND last_read_version >= 0 AND last_read_version <= version),
    CHECK (status IN ('pending','approved','denied','postponed','cancelled')),
    CHECK (support_status IN ('not_required','pending','submitted','verified','rejected')),
    CHECK (status <> 'approved' OR (is_paid IS NOT NULL AND decided_by_user_id IS NOT NULL AND decided_at IS NOT NULL)),
    CHECK (return_verified_at IS NULL OR (returned_at IS NOT NULL AND return_verified_by_user_id IS NOT NULL)),
    CHECK (returned_at IS NULL OR returned_at >= starts_at)
);
-- CHECK debe rechazar NULL explícitamente, también al actualizar una instalación previa.
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'employee_leave_decision_reason_check'
        AND conrelid = 'public.employee_leave_request'::regclass) THEN
        ALTER TABLE public.employee_leave_request ADD CONSTRAINT employee_leave_decision_reason_check
            CHECK (status = 'pending' OR (decision_reason IS NOT NULL AND length(btrim(decision_reason)) > 0));
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS ix_employee_leave_request_tenant ON public.employee_leave_request(tenant_id);
CREATE INDEX IF NOT EXISTS ix_employee_leave_request_inbox ON public.employee_leave_request(tenant_id, branch_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_employee_leave_request_person ON public.employee_leave_request(tenant_id, user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.employee_leave_attachment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES public.tenant(id),
    request_id integer NOT NULL,
    upload_key uuid NOT NULL,
    uploaded_by_user_id integer NOT NULL,
    file_name varchar(150) NOT NULL,
    content_type varchar(64) NOT NULL,
    storage_key varchar(600) NOT NULL,
    size integer NOT NULL CHECK (size > 0 AND size <= 5242880),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, request_id, upload_key),
    FOREIGN KEY (tenant_id, request_id) REFERENCES public.employee_leave_request(tenant_id, id),
    FOREIGN KEY (tenant_id, uploaded_by_user_id) REFERENCES public."user"(tenant_id, id),
    CHECK (content_type IN ('application/pdf','image/jpeg','image/png'))
);
CREATE INDEX IF NOT EXISTS ix_employee_leave_attachment_tenant ON public.employee_leave_attachment(tenant_id);
