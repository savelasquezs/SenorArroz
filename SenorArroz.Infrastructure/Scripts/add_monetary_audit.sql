CREATE OR REPLACE FUNCTION public.audit_current_user_id() RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    raw_value text;
BEGIN
    raw_value := current_setting('app.current_user_id', true);
    IF raw_value IS NULL OR btrim(raw_value) = '' THEN
        RETURN NULL;
    END IF;
    RETURN raw_value::integer;
END;
$$;

