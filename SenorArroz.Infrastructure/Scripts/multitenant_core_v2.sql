    ) THEN
        RAISE EXCEPTION 'multitenant_core_v2: existe un refresh_token sin user valido';
    END IF;

    IF EXISTS (
        SELECT 1 FROM password_reset_token AS token
        LEFT JOIN "user" AS u ON u.id = token.user_id
        WHERE u.id IS NULL
    ) THEN
        RAISE EXCEPTION 'multitenant_core_v2: existe un password_reset_token sin user valido';
