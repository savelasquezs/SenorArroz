        SELECT 1
        FROM "user" AS u
        JOIN branch AS b ON b.id = u.branch_id
        LEFT JOIN tenant AS t ON t.id = b.tenant_id
        WHERE t.id IS NULL
    ) THEN
        RAISE EXCEPTION 'multitenant_core_v2: existe un user cuya branch no tiene tenant valido';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM "user" AS u
        JOIN branch AS b ON b.id = u.branch_id
