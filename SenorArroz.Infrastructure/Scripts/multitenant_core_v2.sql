        RAISE EXCEPTION 'multitenant_core_v2: el tenant 1 debe estar activo y tener access_version valido';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM branch AS b
        LEFT JOIN tenant AS t ON t.id = b.tenant_id
        WHERE b.tenant_id IS NULL OR t.id IS NULL
    ) THEN
        RAISE EXCEPTION 'multitenant_core_v2: existe una branch sin tenant valido';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM "user" AS u
        LEFT JOIN branch AS b ON b.id = u.branch_id
        WHERE b.id IS NULL
    ) THEN
        RAISE EXCEPTION 'multitenant_core_v2: existe un user sin branch valida';
    END IF;

