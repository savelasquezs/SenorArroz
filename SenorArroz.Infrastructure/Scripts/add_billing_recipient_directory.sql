BEGIN;
CREATE TABLE IF NOT EXISTS billing_recipient_profile (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id integer NOT NULL REFERENCES tenant(id) ON DELETE RESTRICT,
 document_type integer NOT NULL CHECK(document_type BETWEEN 1 AND 99),
 identification varchar(32) NOT NULL, name varchar(200) NOT NULL,
 trade_name varchar(200), email varchar(254), address varchar(300), needs_review boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id,id), UNIQUE(tenant_id,document_type,identification)
);
CREATE INDEX IF NOT EXISTS ix_billing_profile_tenant ON billing_recipient_profile(tenant_id);
ALTER TABLE customer_billing_recipient ADD COLUMN IF NOT EXISTS profile_id integer;
DO $constraint$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_customer_billing_profile') THEN
  ALTER TABLE customer_billing_recipient ADD CONSTRAINT fk_customer_billing_profile
   FOREIGN KEY(tenant_id,profile_id) REFERENCES billing_recipient_profile(tenant_id,id) ON DELETE RESTRICT;
 END IF;
END $constraint$;
CREATE INDEX IF NOT EXISTS ix_customer_billing_profile ON customer_billing_recipient(tenant_id,profile_id,customer_id);
CREATE OR REPLACE FUNCTION stamp_billing_profile() RETURNS trigger LANGUAGE plpgsql AS $stamp$
BEGIN
 NEW.updated_at=clock_timestamp();
 RETURN NEW;
END $stamp$;
DROP TRIGGER IF EXISTS stamp_billing_profile ON billing_recipient_profile;
CREATE TRIGGER stamp_billing_profile BEFORE UPDATE ON billing_recipient_profile FOR EACH ROW EXECUTE FUNCTION stamp_billing_profile();

WITH legacy AS (
 SELECT *, CASE WHEN document_type=6 THEN split_part(trim(identification),'-',1) ELSE upper(trim(identification)) END AS normalized
 FROM customer_billing_recipient
), grouped AS (
 SELECT tenant_id,document_type,normalized,
 count(DISTINCT lower(trim(name)))>1 OR count(DISTINCT coalesce(lower(trim(email)),''))>1 AS review
 FROM legacy GROUP BY tenant_id,document_type,normalized
)
INSERT INTO billing_recipient_profile(tenant_id,document_type,identification,name,email,needs_review)
 SELECT DISTINCT ON(l.tenant_id,l.document_type,l.normalized) l.tenant_id,l.document_type,l.normalized,
 left(trim(l.name),200),CASE WHEN g.review THEN NULL ELSE nullif(trim(l.email),'') END,g.review
 FROM legacy l JOIN grouped g USING(tenant_id,document_type,normalized)
 ORDER BY l.tenant_id,l.document_type,l.normalized,l.updated_at DESC,l.id DESC
 ON CONFLICT(tenant_id,document_type,identification) DO NOTHING;
UPDATE customer_billing_recipient r SET profile_id=p.id
 FROM billing_recipient_profile p WHERE r.profile_id IS NULL AND r.tenant_id=p.tenant_id AND r.document_type=p.document_type
 AND (CASE WHEN r.document_type=6 THEN split_part(trim(r.identification),'-',1) ELSE upper(trim(r.identification)) END)=p.identification;

ALTER TABLE billing_recipient_profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE billing_recipient_profile FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON billing_recipient_profile;
CREATE POLICY tenant_isolation ON billing_recipient_profile
 USING(app.is_system_scope() OR tenant_id=app.current_tenant_id())
 WITH CHECK(app.is_system_scope() OR tenant_id=app.current_tenant_id());
DO $grants$
BEGIN
 IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='senorarroz_runtime') THEN
  GRANT SELECT,INSERT,UPDATE ON billing_recipient_profile TO senorarroz_runtime;
  GRANT USAGE,SELECT ON SEQUENCE billing_recipient_profile_id_seq TO senorarroz_runtime;
 END IF;
END $grants$;
COMMIT;
