BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL app.system_scope = 'on';

CREATE UNIQUE INDEX IF NOT EXISTS ux_whatsapp_conversation_tenant_id
    ON public.whatsapp_conversation(tenant_id, id);

CREATE TABLE IF NOT EXISTS public.whatsapp_inbox_label (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES public.tenant(id) ON DELETE RESTRICT,
    name varchar(40) NOT NULL CHECK (btrim(name) <> ''),
    normalized_name varchar(40) NOT NULL,
    color varchar(12) NOT NULL CHECK (color IN ('violet', 'amber', 'orange', 'emerald', 'blue', 'teal', 'rose', 'slate')),
    UNIQUE (tenant_id, id),
    CONSTRAINT ux_whatsapp_inbox_label_name UNIQUE (tenant_id, normalized_name)
);

CREATE TABLE IF NOT EXISTS public.whatsapp_conversation_label (
    tenant_id integer NOT NULL,
    conversation_id integer NOT NULL,
    label_id integer NOT NULL,
    PRIMARY KEY (tenant_id, conversation_id, label_id),
    FOREIGN KEY (tenant_id, conversation_id)
        REFERENCES public.whatsapp_conversation (tenant_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_whatsapp_conversation_label_definition FOREIGN KEY (tenant_id, label_id)
        REFERENCES public.whatsapp_inbox_label (tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_whatsapp_conversation_label_filter
    ON public.whatsapp_conversation_label(tenant_id, label_id, conversation_id);

ALTER TABLE public.whatsapp_inbox_label ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_inbox_label FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_access_policy ON public.whatsapp_inbox_label;
CREATE POLICY tenant_access_policy ON public.whatsapp_inbox_label
    USING (app.is_system_scope() OR tenant_id = app.current_tenant_id())
    WITH CHECK (app.is_system_scope() OR tenant_id = app.current_tenant_id());

ALTER TABLE public.whatsapp_conversation_label ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.whatsapp_conversation_label FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_access_policy ON public.whatsapp_conversation_label;
CREATE POLICY tenant_access_policy ON public.whatsapp_conversation_label
    USING (app.is_system_scope() OR tenant_id = app.current_tenant_id())
    WITH CHECK (app.is_system_scope() OR tenant_id = app.current_tenant_id());

DO $$
BEGIN
    IF to_regrole('senorarroz_runtime') IS NOT NULL THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON public.whatsapp_inbox_label TO senorarroz_runtime;
        GRANT SELECT, INSERT, DELETE ON public.whatsapp_conversation_label TO senorarroz_runtime;
        GRANT USAGE ON SEQUENCE public.whatsapp_inbox_label_id_seq TO senorarroz_runtime;
    END IF;
END $$;

COMMIT;
