BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE UNIQUE INDEX IF NOT EXISTS ux_branch_tenant_id_id ON public.branch (tenant_id, id);

CREATE TABLE IF NOT EXISTS public.delivery_work_phone (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES public.tenant(id) ON DELETE RESTRICT,
    branch_id integer NOT NULL,
    phone varchar(15) NOT NULL CHECK (phone ~ '^[1-9][0-9]{7,14}$'),
    device_installation_id varchar(64) NOT NULL CHECK (btrim(device_installation_id) <> ''),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (tenant_id, branch_id) REFERENCES public.branch (tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT ux_delivery_work_phone_number UNIQUE (tenant_id, phone),
    CONSTRAINT ux_delivery_work_phone_device UNIQUE (tenant_id, device_installation_id)
);

CREATE INDEX IF NOT EXISTS idx_delivery_work_session_device_usage
    ON public.delivery_work_session (tenant_id, branch_id, device_installation_id, started_at);

ALTER TABLE public.delivery_work_phone ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.delivery_work_phone FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_access_policy ON public.delivery_work_phone;
CREATE POLICY tenant_access_policy ON public.delivery_work_phone
    USING (app.is_system_scope() OR tenant_id = app.current_tenant_id())
    WITH CHECK (app.is_system_scope() OR tenant_id = app.current_tenant_id());

DO $$
BEGIN
    IF to_regrole('senorarroz_runtime') IS NOT NULL THEN
        GRANT SELECT, INSERT, UPDATE, DELETE ON public.delivery_work_phone TO senorarroz_runtime;
        GRANT USAGE ON SEQUENCE public.delivery_work_phone_id_seq TO senorarroz_runtime;
    END IF;
END $$;

COMMIT;
