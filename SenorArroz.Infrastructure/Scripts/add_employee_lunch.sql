BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE IF NOT EXISTS public.employee_lunch (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES public.tenant(id),
    branch_id integer NOT NULL,
    user_id integer NOT NULL,
    started_at timestamptz NOT NULL,
    ended_at timestamptz,
    started_by_user_id integer NOT NULL,
    ended_by_user_id integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (tenant_id, branch_id) REFERENCES public.branch(tenant_id, id),
    FOREIGN KEY (tenant_id, user_id) REFERENCES public."user"(tenant_id, id),
    FOREIGN KEY (tenant_id, started_by_user_id) REFERENCES public."user"(tenant_id, id),
    FOREIGN KEY (tenant_id, ended_by_user_id) REFERENCES public."user"(tenant_id, id),
    CHECK (ended_at IS NULL OR ended_at >= started_at),
    CHECK ((ended_at IS NULL) = (ended_by_user_id IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_employee_lunch_open
    ON public.employee_lunch(tenant_id, user_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_employee_lunch_branch_date
    ON public.employee_lunch(tenant_id, branch_id, started_at);
CREATE INDEX IF NOT EXISTS ix_employee_lunch_tenant ON public.employee_lunch(tenant_id);
ALTER TABLE public.employee_lunch ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.employee_lunch FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS employee_lunch_tenant ON public.employee_lunch;
DROP POLICY IF EXISTS tenant_select_policy ON public.employee_lunch;
DROP POLICY IF EXISTS tenant_insert_policy ON public.employee_lunch;
DROP POLICY IF EXISTS tenant_update_policy ON public.employee_lunch;
DROP POLICY IF EXISTS tenant_delete_policy ON public.employee_lunch;
CREATE POLICY tenant_select_policy ON public.employee_lunch FOR SELECT
    USING (tenant_id = app.current_tenant_id() OR app.is_system_scope());
CREATE POLICY tenant_insert_policy ON public.employee_lunch FOR INSERT
    WITH CHECK (tenant_id = app.current_tenant_id() OR app.is_system_scope());
CREATE POLICY tenant_update_policy ON public.employee_lunch FOR UPDATE
    USING (tenant_id = app.current_tenant_id() OR app.is_system_scope())
    WITH CHECK (tenant_id = app.current_tenant_id() OR app.is_system_scope());
CREATE POLICY tenant_delete_policy ON public.employee_lunch FOR DELETE
    USING (tenant_id = app.current_tenant_id() OR app.is_system_scope());

CREATE OR REPLACE FUNCTION public.validate_employee_lunch() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    -- A row write also invalidates an older SERIALIZABLE route-acceptance snapshot.
    UPDATE public."user" SET updated_at = updated_at
      WHERE id = NEW.user_id AND tenant_id = NEW.tenant_id;
    IF EXISTS (SELECT 1 FROM public.employee_lunch l
               WHERE l.tenant_id = NEW.tenant_id AND l.user_id = NEW.user_id AND l.id <> NEW.id
                 AND l.started_at < coalesce(NEW.ended_at, 'infinity'::timestamptz)
                 AND coalesce(l.ended_at, 'infinity'::timestamptz) > NEW.started_at) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'employee_lunch_overlap',
            MESSAGE = 'El empleado ya tiene un almuerzo en ese intervalo.';
    END IF;
    IF NEW.ended_at IS NULL AND EXISTS (
        SELECT 1 FROM public."order" o WHERE o.tenant_id = NEW.tenant_id
          AND o.delivery_man_id = NEW.user_id AND o.status NOT IN ('delivered', 'cancelled')) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'employee_lunch_pending_orders',
            MESSAGE = 'Termina los pedidos pendientes antes de salir a almorzar.';
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS validate_employee_lunch ON public.employee_lunch;
CREATE TRIGGER validate_employee_lunch BEFORE INSERT OR UPDATE ON public.employee_lunch
    FOR EACH ROW EXECUTE FUNCTION public.validate_employee_lunch();

CREATE OR REPLACE FUNCTION public.prevent_lunch_assignment() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    IF NEW.delivery_man_id IS NULL OR NEW.status IN ('delivered', 'cancelled') THEN RETURN NEW; END IF;
    IF TG_OP = 'UPDATE' AND NEW.delivery_man_id IS NOT DISTINCT FROM OLD.delivery_man_id
       AND OLD.status NOT IN ('delivered', 'cancelled') THEN RETURN NEW; END IF;
    UPDATE public."user" SET updated_at = updated_at
      WHERE id = NEW.delivery_man_id AND tenant_id = NEW.tenant_id;
    IF EXISTS (SELECT 1 FROM public.employee_lunch l WHERE l.tenant_id = NEW.tenant_id
                 AND l.user_id = NEW.delivery_man_id AND l.ended_at IS NULL) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'employee_lunch_assignment',
            MESSAGE = 'El domiciliario está almorzando.';
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS prevent_lunch_assignment ON public."order";
CREATE TRIGGER prevent_lunch_assignment BEFORE INSERT OR UPDATE OF delivery_man_id, status ON public."order"
    FOR EACH ROW EXECUTE FUNCTION public.prevent_lunch_assignment();
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'senorarroz_runtime') THEN
        GRANT SELECT, INSERT, UPDATE ON public.employee_lunch TO senorarroz_runtime;
        GRANT USAGE, SELECT ON SEQUENCE public.employee_lunch_id_seq TO senorarroz_runtime;
    END IF;
END $$;
COMMIT;
