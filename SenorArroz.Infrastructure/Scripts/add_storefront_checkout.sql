CREATE TABLE IF NOT EXISTS storefront_checkout (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL,
    public_id character varying(40) NOT NULL,
    idempotency_key character varying(80) NOT NULL,
    branch_id integer NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
    customer_id integer REFERENCES customer(id) ON DELETE SET NULL,
    saved_address_id integer REFERENCES address(id) ON DELETE SET NULL,
    order_id integer REFERENCES "order"(id) ON DELETE SET NULL,
    customer_phone character varying(20) NOT NULL,
    customer_name character varying(150) NOT NULL,
    fulfillment_type character varying(20) NOT NULL,
    address_label character varying(80),
    original_address character varying(500),
    formatted_address character varying(500),
    address_additional_info character varying(500),
    latitude numeric(10,7),
    longitude numeric(10,7),
    delivery_fee integer NOT NULL,
    subtotal integer NOT NULL,
    discount_total integer NOT NULL DEFAULT 0,
    total integer NOT NULL,
    items_json jsonb NOT NULL,
    order_notes character varying(1000),
    applied_benefit_type character varying(30) NOT NULL DEFAULT 'None',
    applied_benefit_source_id integer,
    applied_benefit_label character varying(250),
    applied_benefit_reward_type character varying(30),
    applied_benefit_amount numeric(10,2),
    applied_benefit_snapshot jsonb,
    status character varying(30) NOT NULL DEFAULT 'pending',
    expires_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
    updated_at timestamp with time zone NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_storefront_checkout_public_id
    ON storefront_checkout (public_id);
CREATE UNIQUE INDEX IF NOT EXISTS ux_storefront_checkout_idempotency_key
    ON storefront_checkout (idempotency_key);
CREATE INDEX IF NOT EXISTS ix_storefront_checkout_customer_status
    ON storefront_checkout (tenant_id, customer_phone, status);

ALTER TABLE wompi_payment_attempt
    ALTER COLUMN order_id DROP NOT NULL,
    ADD COLUMN IF NOT EXISTS storefront_checkout_id integer;

ALTER TABLE wompi_payment_attempt
    DROP CONSTRAINT IF EXISTS wompi_payment_attempt_storefront_checkout_id_fkey;
ALTER TABLE wompi_payment_attempt
    ADD CONSTRAINT wompi_payment_attempt_storefront_checkout_id_fkey
    FOREIGN KEY (storefront_checkout_id) REFERENCES storefront_checkout(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS ix_wompi_payment_attempt_storefront_checkout
    ON wompi_payment_attempt (storefront_checkout_id);

