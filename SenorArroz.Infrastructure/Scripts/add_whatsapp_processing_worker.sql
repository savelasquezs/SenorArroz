BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public'
        AND tablename = 'whatsapp_realtime_event' AND policyname = 'tenant_isolation') THEN
        CREATE POLICY tenant_isolation ON whatsapp_realtime_event
        USING (app.is_system_scope() OR tenant_id = app.current_tenant_id())
        WITH CHECK (app.is_system_scope() OR tenant_id = app.current_tenant_id());
    END IF;
END;
