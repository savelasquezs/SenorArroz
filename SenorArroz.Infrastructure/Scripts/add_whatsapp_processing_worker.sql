ALTER TABLE whatsapp_webhook_event
    ADD COLUMN IF NOT EXISTS processing_state varchar(20) NOT NULL DEFAULT 'legacy',
    ADD COLUMN IF NOT EXISTS deduplication_key varchar(64),
    ADD COLUMN IF NOT EXISTS partition_key varchar(64),
    ADD COLUMN IF NOT EXISTS protected_payload text,
    ADD COLUMN IF NOT EXISTS processing_attempts integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS lease_token uuid,
    ADD COLUMN IF NOT EXISTS lease_until timestamptz,
    ADD COLUMN IF NOT EXISTS next_attempt_at timestamptz,
    ADD COLUMN IF NOT EXISTS processing_error varchar(100);

CREATE UNIQUE INDEX IF NOT EXISTS ux_whatsapp_webhook_deduplication
    ON whatsapp_webhook_event(tenant_id, deduplication_key) WHERE deduplication_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_whatsapp_webhook_queue
    ON whatsapp_webhook_event(processing_state, next_attempt_at, id);
CREATE INDEX IF NOT EXISTS ix_whatsapp_webhook_partition
    ON whatsapp_webhook_event(tenant_id, partition_key, id);

CREATE TABLE IF NOT EXISTS whatsapp_realtime_event (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES tenant(id),
    conversation_id integer NOT NULL,
    event_name varchar(80) NOT NULL,
    payload jsonb NOT NULL,
    groups text[] NOT NULL DEFAULT ARRAY[]::text[],
    delivered_to text[] NOT NULL DEFAULT ARRAY[]::text[],
    created_at timestamptz NOT NULL DEFAULT NOW(),
    updated_at timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_whatsapp_realtime_event_created ON whatsapp_realtime_event(created_at);
CREATE INDEX IF NOT EXISTS ix_whatsapp_realtime_event_tenant ON whatsapp_realtime_event(tenant_id);
ALTER TABLE whatsapp_realtime_event ENABLE ROW LEVEL SECURITY;
ALTER TABLE whatsapp_realtime_event FORCE ROW LEVEL SECURITY;
