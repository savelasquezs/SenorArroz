CREATE TABLE IF NOT EXISTS cash_vault_movement (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    branch_id integer NOT NULL,
    bank_id integer NOT NULL,
    kind integer NOT NULL,
    amount numeric(12,2) NOT NULL,
    note character varying(500) NULL,
    created_by_id integer NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    updated_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    CONSTRAINT "PK_cash_vault_movement" PRIMARY KEY (id),
    CONSTRAINT "FK_cash_vault_movement_branch_branch_id" FOREIGN KEY (branch_id) REFERENCES branch (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_cash_vault_movement_bank_bank_id" FOREIGN KEY (bank_id) REFERENCES bank (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_cash_vault_movement_user_created_by_id" FOREIGN KEY (created_by_id) REFERENCES "user" (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS "IX_cash_vault_movement_branch_id" ON cash_vault_movement (branch_id);
CREATE INDEX IF NOT EXISTS "IX_cash_vault_movement_branch_created" ON cash_vault_movement (branch_id, created_at);
