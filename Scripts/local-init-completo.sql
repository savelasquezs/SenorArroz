-- Tabla deliveryman_advance (AddDeliverymanAdvanceTable)
CREATE TABLE IF NOT EXISTS deliveryman_advance (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    deliveryman_id integer NOT NULL,
    amount numeric(10,2) NOT NULL CHECK (amount > 0),
    notes text,
    created_by integer NOT NULL,
    branch_id integer NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    updated_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    CONSTRAINT "PK_deliveryman_advance" PRIMARY KEY (id),
    CONSTRAINT "FK_deliveryman_advance_user_deliveryman_id" FOREIGN KEY (deliveryman_id) REFERENCES "user" (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_deliveryman_advance_user_created_by" FOREIGN KEY (created_by) REFERENCES "user" (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_deliveryman_advance_branch_branch_id" FOREIGN KEY (branch_id) REFERENCES branch (id) ON DELETE RESTRICT
);

-- Tabla bank_transfer (movimientos entre bancos)
CREATE TABLE IF NOT EXISTS bank_transfer (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    from_bank_id integer NOT NULL,
    to_bank_id integer NOT NULL,
    amount numeric(12,2) NOT NULL,
    note character varying(500),
    created_by_id integer NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    updated_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    CONSTRAINT "PK_bank_transfer" PRIMARY KEY (id),
    CONSTRAINT "FK_bank_transfer_bank_from_bank_id" FOREIGN KEY (from_bank_id) REFERENCES bank (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_bank_transfer_bank_to_bank_id" FOREIGN KEY (to_bank_id) REFERENCES bank (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_bank_transfer_user_created_by_id" FOREIGN KEY (created_by_id) REFERENCES "user" (id) ON DELETE RESTRICT
);

-- Tabla cash_register_closure (cuadre de caja)
CREATE TABLE IF NOT EXISTS cash_register_closure (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    branch_id integer NOT NULL,
    closed_at timestamp with time zone NOT NULL,
    created_by_id integer NOT NULL,
    opening_cash numeric(12,2) NOT NULL DEFAULT 0,
    closing_cash numeric(12,2) NOT NULL DEFAULT 0,
    denomination_counts character varying(500) NOT NULL DEFAULT '{}',
    created_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    updated_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    CONSTRAINT "PK_cash_register_closure" PRIMARY KEY (id),
    CONSTRAINT "FK_cash_register_closure_branch_branch_id" FOREIGN KEY (branch_id) REFERENCES branch (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_cash_register_closure_user_created_by_id" FOREIGN KEY (created_by_id) REFERENCES "user" (id) ON DELETE RESTRICT
);

-- Tabla cash_closure_bank_reconciliation (conciliación por banco en el cuadre)
CREATE TABLE IF NOT EXISTS cash_closure_bank_reconciliation (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    cash_closure_id integer NOT NULL,
    bank_id integer NOT NULL,
    expected_balance numeric(12,2) NOT NULL DEFAULT 0,
    actual_balance numeric(12,2) NOT NULL DEFAULT 0,
    adjustments character varying(2000),
    difference numeric(12,2) NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    updated_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    CONSTRAINT "PK_cash_closure_bank_reconciliation" PRIMARY KEY (id),
    CONSTRAINT "FK_cash_closure_bank_reconciliation_bank_bank_id" FOREIGN KEY (bank_id) REFERENCES bank (id) ON DELETE RESTRICT,
    CONSTRAINT "FK_cash_closure_bank_reconciliation_cash_register_closure_cash_closure_id" FOREIGN KEY (cash_closure_id) REFERENCES cash_register_closure (id) ON DELETE CASCADE
);

-- Tabla cash_closure_informal_loan (préstamos informales en el cuadre)
CREATE TABLE IF NOT EXISTS cash_closure_informal_loan (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    cash_closure_id integer NOT NULL,
    concept character varying(200) NOT NULL,
    amount numeric(12,2) NOT NULL DEFAULT 0,
    created_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    updated_at timestamp with time zone NOT NULL DEFAULT (NOW()),
    CONSTRAINT "PK_cash_closure_informal_loan" PRIMARY KEY (id),
    CONSTRAINT "FK_cash_closure_informal_loan_cash_register_closure_cash_closure_id" FOREIGN KEY (cash_closure_id) REFERENCES cash_register_closure (id) ON DELETE CASCADE
);

