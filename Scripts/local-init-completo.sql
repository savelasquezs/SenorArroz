CREATE TABLE IF NOT EXISTS reservation_deposit (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    order_id integer NOT NULL,
    branch_id integer NOT NULL,
    amount numeric(18,2) NOT NULL,
    is_effective boolean NOT NULL DEFAULT false,
    bank_id integer,
    app_id integer,
    received_at timestamp with time zone NOT NULL,
    received_by_id integer NOT NULL,
    notes text,
    created_at timestamp with time zone NOT NULL DEFAULT NOW(),
    updated_at timestamp with time zone NOT NULL DEFAULT NOW(),
    CONSTRAINT "PK_reservation_deposit" PRIMARY KEY (id),
    CONSTRAINT "FK_reservation_deposit_order" FOREIGN KEY (order_id) REFERENCES "order"(id) ON DELETE RESTRICT,
    CONSTRAINT "FK_reservation_deposit_branch" FOREIGN KEY (branch_id) REFERENCES branch(id) ON DELETE RESTRICT,
    CONSTRAINT "FK_reservation_deposit_bank" FOREIGN KEY (bank_id) REFERENCES bank(id) ON DELETE RESTRICT,
    CONSTRAINT "FK_reservation_deposit_app" FOREIGN KEY (app_id) REFERENCES app(id) ON DELETE RESTRICT,
    CONSTRAINT "FK_reservation_deposit_user" FOREIGN KEY (received_by_id) REFERENCES "user"(id) ON DELETE RESTRICT
);

